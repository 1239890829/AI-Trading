"""市场交易规则单点（涨跌停幅度）。

历史上 breadth / sentiment engine / data_quality.validator 各自手写一份
涨跌停判定（逐行相同、靠 docstring 注释约定同步）——2026-09-07 健康度审查
R1 收口为单一实现。注意 halt_risk.limit_pct(board) 是「板块键」体系
（board 字符串另服务基准指数映射），属不同抽象不强行合并。
"""
from __future__ import annotations


def limit_pct(symbol: str, name: str | None = None) -> float:
    """涨跌停幅度（百分数）：创业板/科创板 20、北交所 30、主板 10。

    **ST 不再降档（2026-07-06 起）**：沪深交易所 2026-04-24 修订《交易规则》、
    7/6 正式生效——主板风险警示股（ST/*ST）涨跌幅由 5% 放宽至 10%，与主板
    普通股并轨（涉沪 69 只 + 深 81 只）；创业板/科创板 ST 维持 20%、北交所
    维持 30%（注册制后不因风险警示降档）。

    因此本函数的返回值**只取决于代码段**，`name` 参数保留以兼容既有调用签名
    （breadth / validator / sentiment / pre_limit_radar 等仍传名称）——保留而非
    删除是为了给「并轨」留显式落点：若未来规则回退，改动点在此一处可见。

    返回百分数（20.0）；validator 的小数口径自行 /100。

    **代码段口径（2026-09-11 补齐，前端 lib/price-limit.ts 同步）**
    - 20%：创业板 300/301/**302**、科创板 688/689。302 段此前漏收（旧列表只到 301）
      ⇒ 后端判 10%、前端判 20%，**实测已漂移**：302132.SZ 在 2023-02 / 2025-05
      多次收 +20.01% 触板（marketdb daily_k 实测），确认 302 属 20% 板块。
    - 30%：北交所普通股票 **43/83/87/88**/92。88 段依《北京证券交易所
      全国中小企业股份转让系统证券代码、证券简称编制指引》第七条（普通股票
      首两位为 83、87、**88**）——前端早已含 88、后端漏收，双端 golden 无 88 样本
      故从未报警。
    - 10%：主板（含 ST/*ST）兜底。

    ⚠️ **边界（勿踩）**：88 段是**歧义段**——同花顺板块指数（本项目题材目录
    `theme.code`，实测 885xxx/886xxx）也落在 88 段，而**指数无涨跌停概念**。
    本函数只服务**个股** symbol：调用方不得把板块指数/大盘指数传进来
    （前端 `priceLimitPct` 用指数前缀守卫返回 null 三态；后端若要处理指数需另立函数，
    不要用本函数兜底 10 假装有值）。新股上市初期等特殊阶段未在此展开
    （N 前缀豁免由 breadth 的容差逻辑处理）。
    """
    sym = str(symbol or "")
    if sym.startswith(("300", "301", "302", "688", "689")):
        return 20.0
    if sym.startswith(("43", "83", "87", "88", "92")):
        return 30.0
    # 主板（含 ST/*ST）：并轨后统一 10%（此前 ST 为 5%）
    return 10.0
